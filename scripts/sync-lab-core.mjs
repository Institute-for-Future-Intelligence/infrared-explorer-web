#!/usr/bin/env node
/*
 * Copies the pure-TypeScript core of the app's lab projects (the AI Project
 * section, src/labProjects/) from the sibling app repository into
 * src/labProjects/core/, and records which commit the copies came from.
 *
 *   npm run sync:lab-core
 *
 * The files listed below are copied verbatim: they are edited in the app
 * repository (infrared-explorer-app/src/lib/labProjects/) and re-synced here,
 * never changed in place. Two files beside them are the website's own and
 * are not touched:
 *   - core/math.ts: the app's draws formulas with MathJax; the website's shim
 *     renders them with KaTeX behind the same `texToSvg` name.
 *   - core/aiSensors.ts: generated here from the server's AiSensorRec (the
 *     app's file keeps the phone's copy in AsyncStorage, which the web has no
 *     use for); only the `AiSensor` type that types.ts imports.
 *
 * No dependencies; Node 18+. docs: infrared-explorer-app/docs/proposals/
 * ai-projects-web.md §3.1 ("A-class" code).
 */

import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const appRoot = resolve(webRoot, '..', 'infrared-explorer-app');
const srcDir = join(appRoot, 'src', 'lib', 'labProjects');
const outDir = join(webRoot, 'src', 'labProjects', 'core');

/** The files copied as they are (all pure TypeScript: no React Native import). */
const FILES = [
  'types.ts',
  'markdown.ts',
  'replies.ts',
  'pictures.ts',
  'captureNumbers.ts',
  'projectLink.ts',
  'empty.ts',
  'models.ts',
  'reportExport.ts',
  // P1 (the conversation): the status wording, the quota wording, the plan
  // editor's Markdown → HTML half, and the Generate Report gate. runStatus.ts
  // imports `type {RunView} from './runner'`: core/runner.ts (website-side,
  // not synced) re-exports that type from the website's own runner.
  'runStatus.ts',
  'quota.ts',
  'planEditor.ts',
  'reportMaterial.ts',
  // P2 (the captures): the overview's curve compression and sheet layout,
  // the run_code sandbox page (browser code already: the website only swaps
  // its WebView bridge for postMessage, in ../sandboxHost.ts), and the
  // camera-motion / shutter detector read from frame-stats.bin. sandboxPage.ts
  // imports '../heatmap' and '../recordingFormat': ../heatmap.ts and
  // ../recordingFormat.ts beside core/ are the website's shims for them.
  'compress.ts',
  'overviewTiles.ts',
  'sandboxPage.ts',
  // lives beside labProjects/ in the app (src/lib/frameSelection.ts); pure, no imports
  {from: '../frameSelection.ts', to: 'frameSelection.ts'},
];

/** A listing entry's source path (relative to the app's labProjects folder) and its name here. */
const entryOf = (f) => (typeof f === 'string' ? {from: f, to: f} : f);

/** Imports a copied file must not carry: one of these means it is not pure and must not be synced. */
const FORBIDDEN_IMPORT = /from\s+['"](react-native|@react-native|react-native-[^'"]*|mathjax-full)/;

if (!existsSync(srcDir)) {
  console.error(`sync-lab-core: app repository not found at ${srcDir}`);
  process.exit(1);
}
mkdirSync(outDir, { recursive: true });

let commit = 'unknown';
let commitDate = 'unknown';
try {
  commit = execFileSync('git', ['-C', appRoot, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  commitDate = execFileSync('git', ['-C', appRoot, 'show', '-s', '--format=%cI', 'HEAD'], {
    encoding: 'utf8',
  }).trim();
} catch (err) {
  console.warn('sync-lab-core: could not read the app repository commit', err?.message ?? err);
}

for (const entry of FILES) {
  const {from: rel, to: name} = entryOf(entry);
  const from = join(srcDir, rel);
  if (!existsSync(from)) {
    console.error(`sync-lab-core: ${rel} is missing from ${srcDir}`);
    process.exit(1);
  }
  const text = readFileSync(from, 'utf8');
  const bad = text.match(FORBIDDEN_IMPORT);
  if (bad) {
    console.error(`sync-lab-core: ${rel} imports ${bad[1]}; it is not pure and cannot be copied`);
    process.exit(1);
  }
  copyFileSync(from, join(outDir, name));
  console.log(`copied ${name}${rel === name ? '' : ` (from ${rel})`}`);
}

// The AiSensor type alone, as the server keeps a sensor the AI placed on a take
// (functions/src/store.ts AiSensorRec; the app's lib/labProjects/aiSensors.ts
// derives the same shape from its ThermometerProbe).
const aiSensors = `/*
 * GENERATED by scripts/sync-lab-core.mjs — do not edit.
 *
 * A sensor the AI placed on a capture (place_sensors), as the project keeps
 * it: where it reads and how it is drawn. Mirrors AiSensorRec in the app
 * repository's functions/src/store.ts (the app's own aiSensors.ts derives the
 * same shape from its thermometer probe and keeps the phone's copy in
 * AsyncStorage, which the website has no use for).
 */

export interface AiSensor {
  /** Where it reads, as a fraction of the frame's width and height (0–1). */
  x: number;
  y: number;
  name?: string;
  color?: string;
  width?: number;
  shape?: number;
  /** The user restyled it after the AI placed it. */
  userStyled?: boolean;
  aiPlaced?: boolean;
  /** An area sensor: its kind and size; absent for a point. */
  area?: { kind: 'point' | 'rect' | 'ellipse'; w: number; h: number };
}
`;
writeFileSync(join(outDir, 'aiSensors.ts'), aiSensors);
console.log('generated aiSensors.ts');

const source = `# Synced copies — do not edit here

The TypeScript files in this folder (except \`math.ts\` and the generated
\`aiSensors.ts\`) are **verbatim copies** of files in the app repository,
\`infrared-explorer-app/src/lib/labProjects/\`. Edit them there, then run
\`npm run sync:lab-core\` in this repository to bring the change over. A change
made here is lost on the next sync.

- Source commit: \`${commit}\`
- Source commit date: ${commitDate}
- Synced on: ${new Date().toISOString()}

Files copied:

${FILES.map((f) => {
  const {from: rel, to: name} = entryOf(f);
  return rel === name ? `- \`${name}\`` : `- \`${name}\` (from \`src/lib/${rel.replace(/^\.\.\//, '')}\`)`;
}).join('\n')}

Website-side files beside them (not synced):

- \`math.ts\` — KaTeX shim behind the app's \`texToSvg\` name (the app draws formulas with MathJax).
- \`aiSensors.ts\` — generated by the sync script: the \`AiSensor\` type only.
- \`runner.ts\` — a type-only shim: re-exports the website runner's \`RunView\` so the copied \`runStatus.ts\` resolves \`./runner\`.
- \`../heatmap.ts\`, \`../recordingFormat.ts\` (beside this folder) — shims for the \`../heatmap\` and \`../recordingFormat\` the copied \`sandboxPage.ts\` imports: the app's \`paletteRgba\` over the website's palette table, and the frame constants from the website's \`utils/constants.ts\`.

Not synced, rewritten for the website (their app originals import AsyncStorage, the app's cache, its files or a WebView):
\`../consent.ts\` (localStorage note), \`../discard.ts\` (the website's bundle store), \`../runner.ts\`
(httpsCallable.stream + zustand; the browser-tool loop and resumePending as the app's), \`../planEditorDom.ts\`
(the HTML → Markdown half of the app's \`planEditor.ts\` EDITOR_SCRIPT, as TypeScript over the page's DOM).
P2 (the captures): \`../cloudTake.ts\` (the app's \`takeData.ts\`, reading the experiment's cloud copy under
\`recordings/{id}/\` instead of the phone's files), \`../render.ts\` (the app's Skia drawing as Canvas 2D, same
sizes, fonts, palette and scale bar), \`../overview.ts\` and \`../browserTools.ts\` (the app's \`phoneTools.ts\`
\`takeOverview\` and \`look\`, and \`runCode.ts\`; measure / chart / place_sensors are not on the website),
\`../sandboxHost.ts\` (the app's \`CodeSandboxHost.tsx\` + \`sandbox.ts\`: a hidden sandboxed iframe, the page's
WebView bridge swapped for postMessage), \`../codeState.ts\` (the app's, over IndexedDB per account and project).
`;
writeFileSync(join(outDir, 'SOURCE.md'), source);
console.log(`wrote SOURCE.md (${commit.slice(0, 7)})`);
